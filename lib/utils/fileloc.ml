(* --- Datatype definition --- *)

module Prototype = struct

  type t = Filepos.t * Filepos.t [@@deriving eq, ord, show]

  let reprs = [ Filepos.(generated "reprs", generated "reprs") ]
  let copy = Datatype.identity
  let hash loc = fst loc |> Filepos.hash
  let pretty_debug = pp

  let pretty fmt (pos_start, pos_end) =
    if Filepos.is_empty pos_start || Filepos.is_empty pos_end then
      Filepos.pretty fmt pos_start
    else
      let pos_start = Filepos.original pos_start
      and pos_end = Filepos.original pos_end in
      let path1 = Filepos.path pos_start and path2 = Filepos.path pos_end
      and line1 = Filepos.line pos_start and line2 = Filepos.line pos_end
      and col1 = Filepos.column pos_start and col2 = Filepos.column pos_end in
      if Filepath.equal path1 path2 then begin
        Format.fprintf fmt "%s" (Filepath.to_string path1);
        if line1 > 0 && line2 > 0 then
          if line1 <> line2 then
            Format.fprintf fmt ":%d-%d" line1 line2
          else begin
            Format.fprintf fmt ":%d" line1;
            if col1 > 0 && col2 > 0 then begin
              if col1 <> col2 then
                Format.fprintf fmt ":%d-%d" col1 col2
              else
                Format.fprintf fmt ":%d" col1
            end
          end
      end else
        Format.fprintf fmt "%a-%a"
          Filepos.pretty pos_start
          Filepos.pretty pos_end

  let pretty_long fmt (pos_start, pos_end) =
    if Filepos.is_empty pos_start || Filepos.is_empty pos_end then
      Filepos.pretty_long fmt pos_start
    else
      let pos_start = Filepos.original pos_start
      and pos_end = Filepos.original pos_end in
      let path1 = Filepos.path pos_start and path2 = Filepos.path pos_end
      and line1 = Filepos.line pos_start and line2 = Filepos.line pos_end
      and col1 = Filepos.column pos_start and col2 = Filepos.column pos_end
      and generator = Filepos.generated_by pos_start in
      Option.iter (Format.fprintf fmt "generated by %s from ") generator;
      if Filepath.equal path1 path2 then begin
        Format.fprintf fmt "%S" (Filepath.to_string path1);
        if line1 > 0 && line2 > 0 then
          if line1 <> line2 then
            Format.fprintf fmt ", lines %d-%d" line1 line2
          else begin
            Format.fprintf fmt ", line %d" line1;
            if col1 > 0 && col2 > 0 then begin
              if col1 <> col2 then
                Format.fprintf fmt ", characters %d-%d" col1 col2
              else
                Format.fprintf fmt ", character %d" col1
            end
          end
      end else
        (* use the normal (short) format here to avoid printing 2 times the
           generated information. *)
        Format.fprintf fmt "between %a and %a"
          Filepos.pretty pos_start
          Filepos.pretty pos_end

  let pretty_long_with_inclusions fmt loc =
    pretty_long fmt loc;
    List.pretty ~format:"%t" ~item:",@ included from %a" ~sep:"" ~empty:""
      Filepos.pretty_long fmt (Filepos.inclusions (fst loc))

end


include Datatype.Make_with_collections (struct
    include Datatype.Serializable_undefined
    include Prototype
    let name = "Fileloc"
  end)

include Prototype

let generated ?loc generator_name =
  let pos1 = Option.map fst loc
  and pos2 = Option.map snd loc in
  Filepos.generated ?pos:pos1 generator_name,
  Filepos.generated ?pos:pos2 generator_name

(* --- Conversion from/to Lexing.position  --- *)

let of_lexing_pos pos =
  let pos = Filepos.of_lexing_pos pos in
  pos, pos

let of_lexing_loc (pos1, pos2) =
  Filepos.of_lexing_pos pos1, Filepos.of_lexing_pos pos2

let to_lexing_loc (pos1, pos2) =
  Filepos.to_lexing_pos pos1, Filepos.to_lexing_pos pos2


(* --- Accessors  --- *)

let start_pos = fst

let end_pos = snd

let path loc = fst loc |> Filepos.path

let line loc = fst loc |> Filepos.line

let is_empty loc = fst loc |> Filepos.is_empty

(* --- Constructors --- *)

let make ~start_pos ~end_pos = (start_pos, end_pos)

let positions = Fun.id

let from_position pos = (pos, pos)

let range ~start_loc:(loc_start, _) ~end_loc:(_, loc_end) =
  (loc_start, loc_end)

(* --- Datatype with comparison/hash on original source positions  --- *)

module Original = Datatype.Make_with_collections (struct
    include Datatype.Serializable_undefined
    include Prototype
    let name = "Fileloc.Original"
    type t = Filepos.Original.t * Filepos.Original.t [@@deriving eq, ord]
    let hash loc = fst loc |> Filepos.Original.hash
  end)

(* deprecated *)

let unknown = generated "unknown"
